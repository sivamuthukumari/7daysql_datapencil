-- Q7.WHICH COMPLETED DELIVERIES LOOK LONGER THAN FIVE DAYS 

 SELECT 
			D.DELIVERY_ID,DATEDIFF( DAY,O.ORDER_DATE,DELIVERY_DATE) AS DAYS   
			FROM DELIVERIES AS D
			LEFT JOIN  ORDERS AS O 
			ON D.ORDER_ID=O.ORDER_ID
			WHERE 
			D.DELIVERY_STATUS IN ('DELIVERED' ,'DELAYED') 
			AND DATEDIFF( DAY,O.ORDER_DATE,DELIVERY_DATE) > 5
			ORDER BY DAYS DESC
			
--Q8.WHICH CUSTOMER CITIES HAVE A LOGHEST AVRAGE DELIVERY TIME
SELECT 
		C.CITY,
				AVG(
				CAST(
				DATEDIFF(DAY,O.ORDER_DATE,D.DELIVERY_DATE) 
				AS DECIMAL(10,4)
				)) AS DAYS 
		FROM CUSTOMERS AS C
		LEFT JOIN ORDERS AS O
		ON C.CUSTOMER_ID=O.CUSTOMER_ID
		LEFT JOIN  
		DELIVERIES AS D
		ON O.ORDER_ID=D.ORDER_ID
WHERE DELIVERY_STATUS IN( 'DELIVERED','DELAYED')
GROUP BY C.CITY
ORDER BY DAYS DESC

