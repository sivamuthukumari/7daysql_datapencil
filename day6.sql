-- Q2.HOW MANY DELIVERIES BELONG TO EACH DELIVERY STATUS
SELECT DELIVERY_STATUS,COUNT(DELIVERY_ID) AS [COUNT OF ORDER DELIVERIES]
FROM DELIVERIES 
GROUP BY DELIVERY_STATUS

--Q3.ON AVARAGE, HOW MANY DAYS DOES A COMPLETED DELIVERY TAKE

SELECT AVG(
         CAST(
       (T.DAYS) AS DECIMAL(7,5)
	   )) AS AVARAGE_DAY 
	   
	   FROM (
		SELECT 
			DATEDIFF( DAY,O.ORDER_DATE,DELIVERY_DATE) AS DAYS  
			FROM DELIVERIES AS D
			LEFT JOIN  ORDERS AS O 
			ON D.ORDER_ID=O.ORDER_ID
			WHERE D.DELIVERY_STATUS IN('DELIVERED','DELAYED')
            ) AS T


--Q4. WHICH 10 DELIVERED ORDERS TOOK THE LONGEST TO ARRIVE

		SELECT TOP 10
		    O.ORDER_ID,
			D.DELIVERY_ID,DATEDIFF( DAY,O.ORDER_DATE,DELIVERY_DATE) AS DAYS  
			FROM DELIVERIES AS D
			LEFT JOIN  ORDERS AS O 
			ON D.ORDER_ID=O.ORDER_ID
			WHERE  D.DELIVERY_STATUS IN ('DELIVERED','DELAYED')
			ORDER BY DAYS DESC

-- Q5. HOW DOES ORDERS VOULME CHANGE MONTH BY MONTH 

SELECT FORMAT(ORDER_DATE,'yyyy-MM') YEARMONTH,
COUNT(DISTINCT ORDER_ID) CURRENT_MONTHCOUNT,
LAG(COUNT(DISTINCT ORDER_ID),1) OVER( ORDER BY  FORMAT(ORDER_DATE,'yyyy-MM')  ) PREVIOUS_MONTHCOUNT,
COUNT(DISTINCT ORDER_ID) -
LAG(COUNT(DISTINCT ORDER_ID),1) OVER( ORDER BY  FORMAT(ORDER_DATE,'yyyy-MM')  ) AS DIFERTEN_BETWEENORDRES
 FROM ORDERS 
GROUP BY  FORMAT(ORDER_DATE,'yyyy-MM')

