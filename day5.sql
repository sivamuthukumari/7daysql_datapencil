--2.SALES BY THE PRODUCT.GENERATE THE HEIGHEST SALES VALUE PRODECT

SELECT TOP 3 
P.CATEGORY,SUM(OI.QUANTITY*OI.UNIT_PRICE ) AS SALES_VALUE
FROM ORDERS AS O
LEFT JOIN ORDER_ITEMS AS OI 
ON O.ORDER_ID=OI.ORDER_ID
LEFT JOIN PRODUCTS AS P
ON P.PRODUCT_ID=OI.PRODUCT_ID
WHERE STATUS <> 'CANCELLED'
GROUP BY P.category
ORDER BY SALES_VALUE DESC 

--3.TOP 10 PRODUCT BY THE SALES VALUE
SELECT TOP 10
P.product_name,SUM(OI.QUANTITY*OI.UNIT_PRICE) AS SALES_VALUE
FROM ORDERS AS O
LEFT JOIN ORDER_ITEMS AS OI 
ON O.ORDER_ID=OI.ORDER_ID
LEFT JOIN PRODUCTS AS P
ON P.PRODUCT_ID=OI.PRODUCT_ID
WHERE STATUS <> 'CANCELLED'
GROUP BY P.product_name
ORDER BY SALES_VALUE DESC 

--4.TOTAL QUANTITY SOLD BY THE EACH PRODUCT 
SELECT
P.product_name,SUM(OI.QUANTITY)AS SOLD_QUNATITY 
FROM ORDERS AS O
LEFT JOIN ORDER_ITEMS AS OI 
ON O.ORDER_ID=OI.ORDER_ID
LEFT JOIN PRODUCTS AS P
ON P.PRODUCT_ID=OI.PRODUCT_ID
WHERE STATUS <> 'CANCELLED'
GROUP BY P.product_name
ORDER BY SOLD_QUNATITY DESC 
--5.AVARAGE SELLING PRICE BY EACH CATEGORY
SELECT 
		CATEGORY ,AVG(PRICE) AS AVARGE_PRICE
		FROM PRODUCTS
GROUP BY CATEGORY 
ORDER BY AVARGE_PRICE DESC

--6.SALES VALUE  BY EACH SALES CHANNEL 
SELECT 
O.CHANNEL,SUM(OI.QUANTITY*OI.UNIT_PRICE) AS SALES_VALUE
FROM ORDERS AS O
LEFT JOIN ORDER_ITEMS AS OI 
ON O.ORDER_ID=OI.ORDER_ID
WHERE STATUS <> 'CANCELLED'
GROUP BY O.CHANNEL
ORDER BY SALES_VALUE DESC 


--7.ESTIMATE PRODUCT PROFIT
SELECT
    P.PRODUCT_ID,
	P.PRODUCT_NAME,
	SUM(OI.QUANTITY*(OI.UNIT_PRICE-P.COST)) AS ESTIMATE_PROFIT
	FROM ORDERS AS O
	LEFT JOIN ORDER_ITEMS AS OI 
	ON O.ORDER_ID=OI.ORDER_ID
	LEFT JOIN PRODUCTS AS P
	ON P.PRODUCT_ID=OI.PRODUCT_ID
WHERE STATUS <> 'CANCELLED'
GROUP BY P.PRODUCT_NAME,P.PRODUCT_ID
ORDER BY P.PRODUCT_ID
--8.FIND TOP 5 HIGHEST  QUANTITY SOLD BY CATEGORY
SELECT TOP 5
P.CATEGORY,SUM(OI.QUANTITY)AS SOLD_QUANTITY
FROM ORDERS AS O
 LEFT JOIN ORDER_ITEMS AS OI 
ON O.ORDER_ID=OI.ORDER_ID
 LEFT JOIN PRODUCTS AS P
ON P.PRODUCT_ID=OI.PRODUCT_ID
WHERE STATUS <> 'CANCELLED'
GROUP BY P.CATEGORY
ORDER BY SOLD_QUANTITY DESC 

